#!/usr/bin/env node
/**
 * AB#4732: Relic Vault's version numbers, from one place: package.json's `version`.
 *
 *   versionName = package.json version, e.g. 1.2.3 (what Settings and the Play listing show)
 *   versionCode = major * 10000 + minor * 100 + patch, e.g. 10203 (the integer Play orders builds by)
 *
 * So a patch is exactly 1 higher, a minor 100, a major 10000. Minor and patch therefore stay under 100. Play caps
 * versionCode at 2100000000.
 *
 *   node scripts/version.mjs            writes android/version.properties (versionName, versionCode) for the Android
 *                                       build to read, if android/ exists. It never creates android/:
 *                                       `npx cap add android` refuses to run into an existing folder. The shell story
 *                                       (AB#4723) wires build.gradle to it. `npm run build` runs this first.
 *   node scripts/version.mjs --release  the same, and dates CHANGELOG.md's Unreleased notes as this version. This is
 *                                       npm's `version` hook, so `npm version patch` bumps package.json, runs it,
 *                                       commits package.json, package-lock.json and CHANGELOG.md, and tags vX.Y.Z.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Play's own ceiling for versionCode. */
export const MAX_VERSION_CODE = 2_100_000_000;

/** versionCode for a semver version: major*10000 + minor*100 + patch. Throws on anything Play could not order. */
export function versionCode(version) {
  const m = /^(\d+)\.(\d+)\.(\d+)$/.exec(String(version).trim());
  if (!m) throw new Error(`version "${version}" is not MAJOR.MINOR.PATCH (a pre-release has no versionCode)`);
  const [major, minor, patch] = m.slice(1).map(Number);
  if (minor > 99 || patch > 99) throw new Error(`version ${version}: minor and patch must be 0-99, or versionCodes would collide`);
  const code = major * 10000 + minor * 100 + patch;
  if (code < 1 || code > MAX_VERSION_CODE) throw new Error(`version ${version} gives versionCode ${code}, outside Play's 1-${MAX_VERSION_CODE}`);
  return code;
}

/**
 * The android/version.properties file for a version. Bug #4894: it also records the ads mode the web app is being
 * built with (VITE_ADS_MODE, as apps/web/src/game/buildMode.ts reads it), because `npm run build` runs this first, in
 * the same environment as Vite; android/app/build.gradle refuses a release whose web app shows the demo veil.
 */
export function propertiesText(version, env = process.env) {
  const adsMode = env.VITE_ADS_MODE === 'admob' ? 'admob' : 'demo';
  return `# Generated by scripts/version.mjs from package.json (AB#4732). Do not edit: run npm version.\nversionName=${version}\nversionCode=${versionCode(version)}\nadsMode=${adsMode}\n`;
}

/**
 * CHANGELOG.md with its Unreleased notes dated as `version` (Keep a Changelog): a new `## [version] - date` section
 * under an emptied `## [Unreleased]`. A release with nothing written under Unreleased still gets an entry.
 */
export function releaseChangelog(text, version, date) {
  const heading = /^## \[Unreleased\][^\n]*\n/m;
  const found = heading.exec(text);
  if (!found) throw new Error('CHANGELOG.md has no "## [Unreleased]" heading to release');
  if (new RegExp(`^## \\[${version.replace(/\./g, '\\.')}\\]`, 'm').test(text)) throw new Error(`CHANGELOG.md already has ${version}`);
  const start = found.index + found[0].length;
  const next = text.slice(start).search(/^## \[/m);
  const end = next < 0 ? text.length : start + next;
  let notes = text.slice(start, end).trim();
  if (!/^\s*[-*] /m.test(notes)) notes = '### Changed\n\n- No notable changes.';
  return `${text.slice(0, start)}\n## [${version}] - ${date}\n\n${notes}\n\n${text.slice(end).replace(/^\n+/, '')}`.replace(/\n{3,}/g, '\n\n');
}

function main(argv) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
  const code = versionCode(version);
  const android = join(root, 'android');
  if (existsSync(android)) {
    writeFileSync(join(android, 'version.properties'), propertiesText(version));
    console.log(`android/version.properties: versionName ${version}, versionCode ${code}, ads ${process.env.VITE_ADS_MODE === 'admob' ? 'admob' : 'demo (VITE_ADS_MODE is not admob)'}`);
  } else {
    console.log(`versionName ${version}, versionCode ${code} (no android/ yet: nothing written)`);
  }
  if (argv.includes('--release')) {
    const file = join(root, 'CHANGELOG.md');
    const date = new Date().toISOString().slice(0, 10);
    writeFileSync(file, releaseChangelog(readFileSync(file, 'utf8'), version, date));
    console.log(`CHANGELOG.md: ${version} - ${date}`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
